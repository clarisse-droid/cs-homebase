import Link from "next/link";
import { redirect } from "next/navigation";
import { loadPortfolio } from "@/lib/server/portfolio";
import { Badge, Card, Empty, fmtDate } from "@/components/ui";
import { SuggestionButtons, TaskCheck } from "@/components/client-bits";
import { createTask } from "@/app/actions";

export default async function Tasks({ searchParams }: { searchParams: { view?: string; client?: string } }) {
  const p = await loadPortfolio();
  if (!p.user) redirect("/login");
  const today = p.now.toISOString().slice(0, 10);
  const name = (id: string | null) => (id ? p.views.find((v) => v.client.mondayItemId === id)?.client.name ?? id : "—");
  const view = searchParams.view ?? "open";
  let tasks = p.cs.tasks.filter((t) => !searchParams.client || t.clientId === searchParams.client);
  if (view === "open") tasks = tasks.filter((t) => t.status === "open");
  if (view === "overdue") tasks = tasks.filter((t) => t.status === "open" && t.dueDate && t.dueDate < today);
  if (view === "escalations") tasks = tasks.filter((t) => t.isEscalation && t.status === "open");
  if (view === "done") tasks = tasks.filter((t) => t.status === "done");
  // Order: priority (urgent → low), then the client's last touch (oldest / never first), then due date.
  const RANK: Record<string, number> = { urgent: 0, high: 1, medium: 2, low: 3 };
  const touchOf = (id: string | null) => (id ? p.views.find((v) => v.client.mondayItemId === id)?.client.lastTouchDate ?? null : null);
  const byTouch = (a: string | null, b: string | null) => (a ?? "0000").localeCompare(b ?? "0000");
  const order = <T extends { priority: string; clientId: string | null }>(a: T, b: T) => (RANK[a.priority] ?? 9) - (RANK[b.priority] ?? 9) || byTouch(touchOf(a.clientId), touchOf(b.clientId));
  tasks.sort((a, b) => order(a, b) || (a.dueDate ?? "9999").localeCompare(b.dueDate ?? "9999"));
  const pending = p.cs.suggestions.filter((s) => s.status === "pending").sort(order);
  const touchLabel = (id: string | null) => (id ? (touchOf(id) ? `last touch ${fmtDate(touchOf(id))}` : "no touch recorded") : null);
  const canWrite = p.user.role !== "viewer";
  const active = p.views.filter((v) => v.isActive).sort((a, b) => a.client.name.localeCompare(b.client.name));

  return (
    <div className="space-y-6">
      <div><h1 className="text-xl font-semibold tracking-tight">CS tasks</h1><p className="text-sm muted">Your own follow-ups. Stored in this app only, separate from Operations&apos; Monday tasks. Sorted by priority, then by the client&apos;s last touch (longest without contact first).</p></div>

      <Card title={`Suggested tasks awaiting approval (${pending.length})`} action={<span className="text-xs faint">Generated by rules on sync, or by Claude from a summary. Nothing becomes a task without approval.</span>}>
        {pending.length === 0 ? <Empty>No pending suggestions.</Empty> : (
          <ul className="divide-y divide-stone-100 dark:divide-zinc-800">
            {pending.map((s) => (
              <li key={s.id} className="flex flex-wrap items-start justify-between gap-3 px-5 py-3 text-sm">
                <div className="min-w-0 flex-1">
                  <div className="flex items-center gap-2"><Badge tone={s.ruleId === "ai" ? "amber" : "blue"}>{s.ruleId === "ai" ? "AI recommendation" : `Rule: ${s.ruleId}`}</Badge><Badge tone={s.priority === "high" ? "red" : s.priority === "medium" ? "amber" : "gray"}>{s.priority}</Badge>{s.clientId && <Link className="link" href={`/clients/${s.clientId}`}>{name(s.clientId)}</Link>}</div>
                  <div className="mt-1 font-medium">{s.title}</div>
                  {s.clientId && <div className="text-xs faint">{touchLabel(s.clientId)}</div>}
                  <div className="text-xs muted">{s.rationale}</div>
                </div>
                {canWrite && <SuggestionButtons id={s.id} />}
              </li>
            ))}
          </ul>
        )}
      </Card>

      <div className="flex flex-wrap gap-2">
        {[["open", "Open"], ["overdue", "Overdue"], ["escalations", "Escalations"], ["done", "Completed"], ["all", "All"]].map(([k, l]) => <Link key={k} href={`/tasks?view=${k}`} className={`btn text-xs ${view === k ? "ring-2 ring-brand-500/40" : ""}`}>{l}</Link>)}
      </div>

      <div className="grid gap-6 lg:grid-cols-3">
        <Card className="lg:col-span-2" title={`${tasks.length} task(s)`}>
          {tasks.length === 0 ? <Empty>Nothing here.</Empty> : (
            <ul className="divide-y divide-stone-100 dark:divide-zinc-800">
              {tasks.map((t) => (
                <li key={t.id} className="flex items-start gap-3 px-5 py-3 text-sm">
                  {canWrite && <TaskCheck id={t.id} done={t.status === "done"} />}
                  <div className="flex-1">
                    <div className={t.status === "done" ? "line-through faint" : ""}>{t.title} {t.isEscalation && <Badge tone="red">escalation</Badge>} {t.origin === "ai_approved" && <Badge tone="amber">approved suggestion</Badge>}</div>
                    <div className="text-xs muted">{t.clientId ? <Link href={`/clients/${t.clientId}`} className="link">{name(t.clientId)}</Link> : "General"} · {t.priority}{t.clientId ? ` · ${touchLabel(t.clientId)}` : ""} · <span className={t.status === "open" && t.dueDate && t.dueDate < today ? "text-rose-600" : ""}>due {fmtDate(t.dueDate)}</span></div>
                    {t.notes && <div className="mt-0.5 text-xs faint">{t.notes}</div>}
                  </div>
                </li>
              ))}
            </ul>
          )}
        </Card>
        {canWrite && (
          <Card title="New task">
            <form action={createTask} className="space-y-2 px-5 py-4">
              <input name="title" required className="input" placeholder="What needs doing?" />
              <select name="clientId" className="input"><option value="">No client</option>{active.map((v) => <option key={v.client.mondayItemId} value={v.client.mondayItemId}>{v.client.name}</option>)}</select>
              <select name="priority" className="input" defaultValue="medium"><option>low</option><option>medium</option><option>high</option><option>urgent</option></select>
              <input type="date" name="dueDate" className="input" />
              <textarea name="notes" rows={2} className="input" placeholder="Notes" />
              <label className="flex items-center gap-2 text-xs"><input type="checkbox" name="isEscalation" /> Escalation</label>
              <button className="btn-primary w-full justify-center">Create</button>
            </form>
          </Card>
        )}
      </div>
    </div>
  );
}
